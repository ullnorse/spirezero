#!/usr/bin/env python3
"""Generate the display tables in crates/sts2-core/src/content/tables/ from the decomp.

The tables hold only numbers and ids the game declares (move intents, relic and potion
`CanonicalVars`), so the TUI can show a monster's intent and fill in relic and potion text:

- `intents.rs`: every `new MoveState("ID", Method, intents...)` of `Models.Monsters/*.cs`.
- `relic_vars.rs`, `potion_vars.rs`, `event_vars.rs`, `power_vars.rs`: every `CanonicalVars`
  entry of `Models.{Relics,Potions,Events,Powers}/*.cs` (name and literal
  `BaseValue`; a `StringVar`'s fixed text: another model's title or a literal).

Run it after porting content that changes these (the tables cover every decomp model, ported
or not, so a new port needs no rerun): `python3 tools/gen_tables.py [REF_DIR]`.
"""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "crates/sts2-core/src/content/tables"
REF = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "ref"
DECOMP = REF / "decomp"

HEADER = "// Generated by tools/gen_tables.py from the game's {what}; do not edit.\n\n"

ASCENSION_LEVELS = [
    "None", "SwarmingElites", "WearyTraveler", "Poverty", "TightBelt", "AscendersBane",
    "Inflation", "Scarcity", "ToughEnemies", "DeadlyEnemies", "DoubleBoss",
]


def screaming_snake(camel: str) -> str:
    """`ModelId.Entry` of a class name, as `build.rs` derives it."""
    out = []
    for i, c in enumerate(camel):
        if i > 0 and c.isupper():
            prev = camel[i - 1]
            next_lower = i + 1 < len(camel) and camel[i + 1].islower()
            if not prev.isupper() or next_lower:
                out.append("_")
        out.append(c.upper())
    return "".join(out)


def closing(src: str, at: int) -> int:
    """The index of the `)` matching the `(` at `at`."""
    depth = 0
    for i in range(at, len(src)):
        if src[i] == "(":
            depth += 1
        elif src[i] == ")":
            depth -= 1
            if depth == 0:
                return i
    raise ValueError("unbalanced parentheses")


def split_args(args: str) -> list[str]:
    """Top-level comma-separated arguments."""
    out, depth, cur = [], 0, ""
    for c in args:
        if c in "([{<":
            depth += 1
        elif c in ")]}>":
            depth -= 1
        if c == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += c
    if cur.strip():
        out.append(cur.strip())
    return out


def constructions(src: str) -> list[tuple[str, str]]:
    """The top-level `new Type(args)` expressions in `src`: (type, args)."""
    out, end = [], -1
    for m in re.finditer(r"new (\w+(?:<\w+>)?)\(", src):
        if m.start() <= end:
            continue
        close = closing(src, m.end() - 1)
        out.append((m.group(1), src[m.end():close]))
        end = close
    return out


def literal_int(text: str) -> int | None:
    m = re.fullmatch(r"(-?\d+)m?", text.strip())
    return int(m.group(1)) if m else None


def literal_decimal(text: str) -> str | None:
    """A decimal literal as `(mantissa, scale)` Rust arguments."""
    m = re.fullmatch(r"(-?\d+)(?:\.(\d+))?m?", text.strip())
    if not m:
        return None
    frac = m.group(2) or ""
    return f"{int(m.group(1) + frac)}, {len(frac)}"


# ---------------------------------------------------------------------------------------------
# Intents

INTENTS = {
    "SingleAttackIntent": "SingleAttack",
    "MultiAttackIntent": "MultiAttack",
    "DeathBlowIntent": "DeathBlow",
    "BuffIntent": "Buff",
    "DefendIntent": "Defend",
    "EscapeIntent": "Escape",
    "HealIntent": "Heal",
    "HiddenIntent": "Hidden",
    "SummonIntent": "Summon",
    "SleepIntent": "Sleep",
    "StunIntent": "Stun",
    "CardDebuffIntent": "CardDebuff",
}


def card_count(arg: str, src: str, where: str) -> str:
    """A `StatusIntent`'s card count: a literal or an `int` property of the monster."""
    n = literal_int(arg)
    if n is not None:
        return f"CardCount::Fixed({n})"
    m = re.search(rf"\b{arg}\s*=>\s*([^;]+);", src)
    if not m:
        raise SystemExit(f"{where}: unknown StatusIntent count {arg}")
    body = m.group(1).strip()
    n = literal_int(body)
    if n is not None:
        return f"CardCount::Fixed({n})"
    m = re.fullmatch(
        r"AscensionHelper\.GetValueIfAscension\(AscensionLevel\.(\w+),\s*(\d+),\s*(\d+)\)", body
    )
    if not m:
        raise SystemExit(f"{where}: unsupported StatusIntent count {body}")
    level = ASCENSION_LEVELS.index(m.group(1))
    return f"CardCount::Ascension {{ level: {level}, then: {m.group(2)}, otherwise: {m.group(3)} }}"


def intent(kind: str, args: str, src: str, where: str) -> str:
    if kind == "DebuffIntent":
        strong = "strong: true" in args or args.strip() == "true"
        return "Declared::DebuffStrong" if strong else "Declared::Debuff"
    if kind == "StatusIntent":
        return f"Declared::StatusCard({card_count(args, src, where)})"
    if kind not in INTENTS:
        raise SystemExit(f"{where}: unknown intent {kind}")
    return f"Declared::{INTENTS[kind]}"


def gen_intents() -> str:
    rows = {}
    bases = {}
    for path in sorted((DECOMP / "MegaCrit.Sts2.Core.Models.Monsters").glob("*.cs")):
        src = path.read_text()
        monster = screaming_snake(path.stem)
        base = re.search(rf"class {path.stem} : (\w+)", src)
        if base and base.group(1) != "MonsterModel":
            bases[monster] = screaming_snake(base.group(1))
        for m in re.finditer(r"new MoveState\(", src):
            args = split_args(src[m.end():closing(src, m.end() - 1)])
            move_id = args[0].strip('"')
            where = f"{path.stem}.{move_id}"
            intents = []
            for arg in args[2:]:
                for kind, inner in constructions(arg):
                    intents.append(intent(kind, inner, src, where))
            key = (monster, move_id)
            if key in rows and rows[key] != intents:
                raise SystemExit(f"{where}: declared twice with different intents")
            rows[key] = intents
    # A subclass without moves of its own builds its base's (`DecimillipedeSegmentFront`).
    for monster, base in bases.items():
        if not any(m == monster for m, _ in rows):
            for (m, move_id), intents in list(rows.items()):
                if m == base:
                    rows[(monster, move_id)] = intents
    out = HEADER.format(what="`MoveState` declarations (`Models.Monsters/*.cs`)")
    out += "use super::{CardCount, Declared};\n\n"
    out += "/// `(monster ModelId.Entry, MoveState.Id, Intents)`, sorted.\n"
    out += "pub static INTENTS: &[(&str, &str, &[Declared])] = &[\n"
    for (monster, move_id), intents in sorted(rows.items()):
        out += f'    ("{monster}", "{move_id}", &[{", ".join(intents)}]),\n'
    out += "];\n"
    return out


# ---------------------------------------------------------------------------------------------
# Relic and potion vars

DEFAULT_NAMES = {
    "CardsVar": "Cards",
    "EnergyVar": "Energy",
    "DamageVar": "Damage",
    "BlockVar": "Block",
    "GoldVar": "Gold",
    "HealVar": "Heal",
    "MaxHpVar": "MaxHp",
    "HpLossVar": "HpLoss",
    "RepeatVar": "Repeat",
    "StarsVar": "Stars",
    "SummonVar": "Summon",
    "ForgeVar": "Forge",
}


TITLE_KINDS = {
    "Card": "Card",
    "Relic": "Relic",
    "Potion": "Potion",
    "Enchantment": "Enchantment",
    "Affliction": "Affliction",
}


def string_var_text(rest: list[str]) -> str | None:
    """A `StringVar`'s fixed text as a `VarText`: another model's `Title`, or a literal."""
    if not rest:
        return None
    m = re.match(r"ModelDb\.(\w+)<(?:[\w.]+\.)?(\w+)>\(\)\.Title", rest[0])
    if m and m.group(1) in TITLE_KINDS:
        return f'VarText::{TITLE_KINDS[m.group(1)]}("{screaming_snake(m.group(2))}")'
    m = re.fullmatch(r'"([^"]*)"', rest[0].strip())
    if m:
        return f'VarText::Literal("{m.group(1)}")'
    return None


def canonical_vars(src: str, where: str) -> list[tuple[str, str | None]] | None:
    m = re.search(r"CanonicalVars\s*=>", src)
    if not m:
        return None
    body, depth = src[m.end():], 0
    for i, c in enumerate(body):
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        elif c == ";" and depth == 0:
            body = body[:i]
            break
    entries = []
    for kind, args in constructions(body):
        if kind.startswith("_003C"):
            inner = args
            if inner.startswith("new DynamicVar["):
                inner = inner[inner.index("{") + 1:inner.rindex("}")]
            entries.extend(constructions(inner))
        else:
            entries.append((kind, args))
    out = []
    for kind, args in entries:
        parts = split_args(args)
        named = bool(parts) and parts[0].startswith('"')
        if kind == "StringVar":
            out.append((parts[0].strip('"'), None, string_var_text(parts[1:])))
            continue
        if len(parts) > 1 and not named and literal_decimal(parts[0]) is None:
            # A name the model computes (`new GoldVar(_prizeKeys[0], _prizeCosts[0])`).
            continue
        if kind in ("DynamicVar", "IntVar") or named:
            name, value = parts[0].strip('"'), parts[1] if len(parts) > 1 else None
        elif kind.startswith("PowerVar<"):
            name, value = kind[len("PowerVar<"):-1], parts[0]
        elif kind in DEFAULT_NAMES:
            name, value = DEFAULT_NAMES[kind], parts[0]
        else:
            raise SystemExit(f"{where}: unknown var {kind}({args})")
        dec = literal_decimal(value) if value is not None else None
        # A non-literal base (`CombatsLeft`) is set by the model; the relic's data gives it.
        out.append((name, dec, None))
    return out


def gen_vars(kind_dir: str, what: str, static: str) -> str:
    rows = []
    for path in sorted((DECOMP / f"MegaCrit.Sts2.Core.Models.{kind_dir}").glob("*.cs")):
        entries = canonical_vars(path.read_text(), path.stem)
        if entries:
            rows.append((screaming_snake(path.stem), entries))
    out = HEADER.format(what=f"`CanonicalVars` (`Models.{kind_dir}/*.cs`)")
    uses = "ModelVar, VarText" if "VarText::" in str(rows) else "ModelVar"
    out += f"use super::{{{uses}}};\nuse crate::decimal::Decimal;\n\n"
    out += f"/// `({what} ModelId.Entry, CanonicalVars)`, sorted.\n"
    out += f"pub static {static}: &[(&str, &[ModelVar])] = &[\n"
    for model, entries in sorted(rows):
        vals = []
        for name, dec, text in entries:
            value = f"Some(Decimal::new({dec}))" if dec is not None else "None"
            text = f"Some({text})" if text else "None"
            vals.append(f'ModelVar {{ name: "{name}", value: {value}, text: {text} }}')
        out += f'    ("{model}", &[{", ".join(vals)}]),\n'
    out += "];\n"
    return out


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    files = {
        "intents.rs": gen_intents(),
        "relic_vars.rs": gen_vars("Relics", "relic", "RELIC_VARS"),
        "potion_vars.rs": gen_vars("Potions", "potion", "POTION_VARS"),
        "event_vars.rs": gen_vars("Events", "event", "EVENT_VARS"),
        "power_vars.rs": gen_vars("Powers", "power", "POWER_VARS"),
    }
    for name, text in files.items():
        (OUT / name).write_text(text)
    subprocess.run(["rustfmt", "--edition", "2024", *(str(OUT / n) for n in files)], check=True)


if __name__ == "__main__":
    main()
